// Handler is the agent-side implementation the server dispatches to. Streaming
// operations receive a writer whose lines are forwarded to the hub live.
type Handler interface {
	Health() HealthResponse
	Install(ctx context.Context, req InstallRequest, log io.Writer) error
	ApplyCert(ctx context.Context, req CertRequest, log io.Writer) error
	Uninstall(ctx context.Context, req UninstallRequest, log io.Writer) error
	Subscription(format string) ([]byte, error)
}

// UpgradeHandler is implemented by agents that support in-overlay binary
// upgrades. It is optional so a hub can report a clear unsupported response
// when probing an older agent implementation.
type UpgradeHandler interface {
	Upgrade(ctx context.Context, req UpgradeRequest, log io.Writer) error
}

// CoreHandler is implemented by agents that support changing the local
// sing-box core to an exact hub-selected stable release.
type CoreHandler interface {
	ChangeCore(ctx context.Context, req CoreRequest, log io.Writer) error
}

// RelayHandler is implemented by agents that can front another node's traffic.
// Keeping it optional lets a newer Hub report an agent that predates relaying
// instead of failing an install with a routing error.
type RelayHandler interface {
	ApplyRelay(ctx context.Context, req RelayRequest, log io.Writer) error
}

// ProtocolStateHandler is implemented by agents that support full protocol
// editing. Keeping it optional lets a newer Hub diagnose an older Agent
// cleanly instead of changing the base lifecycle interface.
type ProtocolStateHandler interface {
	ProtocolState(context.Context) (ProtocolStateResponse, error)
}

// MonitorHandler is implemented by an agent that has an in-process monitor.
// The Server invokes it only with one of the fixed local monitor paths declared
// by MonitorEndpoint and strips the request query before dispatch.
type MonitorHandler interface {
	MonitorHandler() http.Handler
}

// TrafficUsageHandler is implemented by agents that support reading and
// replacing current-cycle traffic usage. It is separate from MonitorHandler so
// write requests can never be forwarded to the monitor's read-only HTTP mux.
type TrafficUsageHandler interface {
	TrafficUsage(context.Context) (TrafficUsage, error)
	SetTrafficUsage(context.Context, TrafficUsageRequest) (TrafficUsageUpdate, error)
}

// Server exposes Handler over HTTP, guarded by a bearer token.
type Server struct {
	Token   string
	Handler Handler
}

// Mux returns the routed HTTP handler.
func (s *Server) Mux() http.Handler {
	mux := http.NewServeMux()
	s.handle(mux, http.MethodGet, "/api/health", s.handleHealth)
	s.handle(mux, http.MethodGet, "/api/protocol-state", s.handleProtocolState)
	s.handle(mux, http.MethodPost, "/api/install", s.handleInstall)
	s.handle(mux, http.MethodPost, "/api/cert", s.handleCert)
	s.handle(mux, http.MethodPost, "/api/uninstall", s.handleUninstall)
	s.handle(mux, http.MethodPost, "/api/upgrade", s.handleUpgrade)
	s.handle(mux, http.MethodPost, "/api/core", s.handleCore)
	s.handle(mux, http.MethodPost, "/api/relay", s.handleRelay)
	s.handle(mux, http.MethodGet, "/api/subscription", s.handleSubscription)
	mux.HandleFunc("/api/monitor/usage", s.auth(s.handleTrafficUsage))
	for _, endpoint := range monitorEndpoints {
		apiPath, _, _ := endpoint.paths()
		s.handle(mux, http.MethodGet, apiPath, s.handleMonitor(endpoint))
	}
	return securityHeaders(mux)
}

func (s *Server) handle(mux *http.ServeMux, method, path string, next http.HandlerFunc) {
	mux.HandleFunc(path, s.auth(requireMethod(method, next)))
}

func requireMethod(method string, next http.HandlerFunc) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		if r.Method != method {
			w.Header().Set("Allow", method)
			http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
			return
		}
		next(w, r)
	}
}

// securityHeaders applies to successful responses and every error generated by
// the mux, including authentication failures, method errors, and 404s.
func securityHeaders(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Cache-Control", "no-store")
		w.Header().Set("Content-Security-Policy", "default-src 'none'; frame-ancestors 'none'")
		w.Header().Set("Referrer-Policy", "no-referrer")
		w.Header().Set("X-Content-Type-Options", "nosniff")
		w.Header().Set("X-Frame-Options", "DENY")
		next.ServeHTTP(w, r)
	})
}

// auth wraps a handler with constant-time bearer-token verification.
func (s *Server) auth(next http.HandlerFunc) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		values := r.Header.Values("Authorization")
		authorization := ""
		if len(values) == 1 {
			authorization = values[0]
		}
		const prefix = "Bearer "
		token := ""
		if strings.HasPrefix(authorization, prefix) {
			token = strings.TrimPrefix(authorization, prefix)
		}
		if s.Token == "" || token == "" || subtle.ConstantTimeCompare([]byte(token), []byte(s.Token)) != 1 {
			http.Error(w, "unauthorized", http.StatusUnauthorized)
			return
		}
		next(w, r)
	}
}

func (s *Server) handleHealth(w http.ResponseWriter, _ *http.Request) {
	writeJSON(w, s.Handler.Health())
}

func (s *Server) handleProtocolState(w http.ResponseWriter, r *http.Request) {
	handler, ok := s.Handler.(ProtocolStateHandler)
	if !ok {
		http.Error(w, "protocol state is not supported by this agent", http.StatusNotImplemented)
		return
	}
	current, err := handler.ProtocolState(r.Context())
	if err != nil {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}
	writeJSON(w, current)
}

func (s *Server) handleInstall(w http.ResponseWriter, r *http.Request) {
	var req InstallRequest
	if err := decodeJSON(w, r, &req, maxInstallRequestBody); err != nil {
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}
	if err := ValidateInstallSingBoxVersion(req); err != nil {
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}
	streamOperation(w, func(log io.Writer) error {
		return s.Handler.Install(r.Context(), req, log)
	})
}

