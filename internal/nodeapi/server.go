func (s *Server) handleSubscription(w http.ResponseWriter, r *http.Request) {
	format := r.URL.Query().Get("format")
	body, err := s.Handler.Subscription(format)
	if err != nil {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "text/plain; charset=utf-8")
	_, _ = w.Write(body)
}

func (s *Server) handleTrafficUsage(w http.ResponseWriter, r *http.Request) {
	handler, ok := s.Handler.(TrafficUsageHandler)
	if !ok {
		http.Error(w, "traffic usage management is not supported by this agent", http.StatusNotImplemented)
		return
	}
	switch r.Method {
	case http.MethodGet:
		usage, err := handler.TrafficUsage(r.Context())
		if err != nil {
			http.Error(w, err.Error(), http.StatusInternalServerError)
			return
		}
		if err := ValidateTrafficUsage(usage); err != nil {
			http.Error(w, err.Error(), http.StatusInternalServerError)
			return
		}
		writeJSON(w, usage)
	case http.MethodPut:
		var wire struct {
			InBytes            *uint64 `json:"inBytes"`
			OutBytes           *uint64 `json:"outBytes"`
			ExpectedCycleStart *int64  `json:"expectedCycleStart"`
		}
		if err := decodeStrictJSON(w, r, &wire, maxTrafficUsageRequestBody); err != nil {
			http.Error(w, err.Error(), http.StatusBadRequest)
			return
		}
		if wire.InBytes == nil || wire.OutBytes == nil || wire.ExpectedCycleStart == nil {
			http.Error(w, "inBytes, outBytes, and expectedCycleStart are required", http.StatusBadRequest)
			return
		}
		req := TrafficUsageRequest{
			InBytes: *wire.InBytes, OutBytes: *wire.OutBytes,
			ExpectedCycleStart: *wire.ExpectedCycleStart,
		}
		if err := ValidateTrafficUsageRequest(req); err != nil {
			http.Error(w, err.Error(), http.StatusBadRequest)
			return
		}
		update, err := handler.SetTrafficUsage(r.Context(), req)
		if err != nil {
			status := http.StatusInternalServerError
			if IsTrafficCycleConflict(err) {
				status = http.StatusConflict
			}
			http.Error(w, err.Error(), status)
			return
		}
		if err := ValidateTrafficUsageUpdate(update); err != nil {
			http.Error(w, err.Error(), http.StatusInternalServerError)
			return
		}
		if update.Applied.InBytes != req.InBytes || update.Applied.OutBytes != req.OutBytes ||
			update.Applied.CycleStart != req.ExpectedCycleStart {
			http.Error(w, "traffic usage handler returned a result that does not match the request", http.StatusInternalServerError)
			return
		}
		writeJSON(w, update)
	default:
		w.Header().Set("Allow", http.MethodGet+", "+http.MethodPut)
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
	}
}

func (s *Server) handleMonitor(endpoint MonitorEndpoint) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		provider, ok := s.Handler.(MonitorHandler)
		if !ok {
			http.Error(w, "agent monitor is not supported", http.StatusNotImplemented)
			return
		}
		handler := provider.MonitorHandler()
		if handler == nil {
			http.Error(w, "agent monitor is not running", http.StatusServiceUnavailable)
			return
		}
		_, handlerPath, ok := endpoint.paths()
		if !ok {
			http.Error(w, "monitor endpoint not found", http.StatusNotFound)
			return
		}

		// Never pass a caller-controlled path or query to the monitor. In
		// particular, dropping `source` prevents its multi-source handler from
		// proxying to a URL stored in a remote snapshot.
		//
		// One endpoint drills into a single address, so it needs a parameter.
		// The address is parsed and written back out rather than forwarded, so
		// what reaches the monitor is still a value this process produced.
		query := ""
		if endpoint == MonitorIPDetail {
			address, err := netip.ParseAddr(strings.TrimSpace(r.URL.Query().Get("ip")))
			if err != nil {
				http.Error(w, "ip must be an IP address", http.StatusBadRequest)
				return
			}
			query = url.Values{"ip": []string{address.String()}}.Encode()
		}
		monitorRequest := r.Clone(r.Context())
		monitorRequest.Method = http.MethodGet
		monitorRequest.URL.Path = handlerPath
		monitorRequest.URL.RawPath = ""
		monitorRequest.URL.RawQuery = query
		monitorRequest.RequestURI = handlerPath
		monitorRequest.Header = r.Header.Clone()
		monitorRequest.Header.Del("Authorization")
		monitorRequest.Body = http.NoBody
		handler.ServeHTTP(w, monitorRequest)
	}
}

const (
	maxInstallRequestBody      int64 = 4 << 20
	maxCertRequestBody         int64 = 2 << 20
	maxUninstallRequestBody    int64 = 16 << 10
	maxCoreRequestBody         int64 = 4 << 10
	maxTrafficUsageRequestBody int64 = 4 << 10
	// A relay job is a handful of small records per landing node, and a hub
	// fronting a large fleet through one relay is still far inside this.
	maxRelayRequestBody int64 = 256 << 10
	// []byte expands by 4/3 when JSON/base64 encoded. Leave a small allowance
	// for field names and the version/digest strings.
	maxUpgradeRequestBody int64 = (MaxAgentBinarySize+2)/3*4 + 4096
)

// decodeJSON accepts exactly one JSON value, bounded before decoding. JSON
// whitespace after the value is permitted; a second value or any other
// trailing bytes are rejected.
func decodeJSON(w http.ResponseWriter, r *http.Request, dst any, maxBytes int64) error {
	return decodeJSONWithOptions(w, r, dst, maxBytes, false)
}

func decodeStrictJSON(w http.ResponseWriter, r *http.Request, dst any, maxBytes int64) error {
	return decodeJSONWithOptions(w, r, dst, maxBytes, true)
}

func decodeJSONWithOptions(w http.ResponseWriter, r *http.Request, dst any, maxBytes int64, strict bool) error {
	if r.Body == nil {
		return fmt.Errorf("request body is required")
	}
	r.Body = http.MaxBytesReader(w, r.Body, maxBytes)
	decoder := json.NewDecoder(r.Body)
	if strict {
		decoder.DisallowUnknownFields()
	}
	if err := decoder.Decode(dst); err != nil {
		return fmt.Errorf("decode JSON request: %w", err)
	}
	var extra any
	if err := decoder.Decode(&extra); err != io.EOF {
		if err == nil {
			return fmt.Errorf("request body must contain exactly one JSON value")
		}
		return fmt.Errorf("invalid data after JSON request: %w", err)
	}
	return nil
}

// streamOperation runs op, forwarding its log output to the client as it is
// produced, and finishes with a status sentinel line the client parses.
func streamOperation(w http.ResponseWriter, op func(log io.Writer) error) {
	w.Header().Set("Content-Type", "text/plain; charset=utf-8")
	w.Header().Set("X-Content-Type-Options", "nosniff")
	flusher, _ := w.(http.Flusher)
	lw := &lineFlushWriter{w: w, flusher: flusher}
	err := op(lw)
	if err != nil {
		fmt.Fprintf(w, "%s%s\n", errorSentinelPrefix, sanitizeLine(err.Error()))
	} else {
		fmt.Fprintf(w, "%s\n", doneSentinel)
	}
	if flusher != nil {
		flusher.Flush()
	}
}

// lineFlushWriter flushes after every write so the hub sees live progress.
type lineFlushWriter struct {
	w       io.Writer
	flusher http.Flusher
}

func (l *lineFlushWriter) Write(p []byte) (int, error) {
	n, err := l.w.Write(p)
	if l.flusher != nil {
		l.flusher.Flush()
	}
	return n, err
}

// sanitizeLine collapses newlines so an error message cannot masquerade as the
// sentinel or split into multiple log lines.
func sanitizeLine(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "\r", " "), "\n", " ")
}

func writeJSON(w http.ResponseWriter, v any) {
	w.Header().Set("Content-Type", "application/json")
	_ = json.NewEncoder(w).Encode(v)
}
